export function getDemoDataset() {
  const seenDomains = new Set<string>();
  const validList: CompanyWithPrecomputedEvidence[] = [];
  const duplicates: CompanyWithPrecomputedEvidence[] = [];

  for (const item of DEMO_COMPANIES_DATA) {
    if (seenDomains.has(item.company.normalizedDomain)) {
      duplicates.push(item);
    } else {
      seenDomains.add(item.company.normalizedDomain);
      const domain = item.company.normalizedDomain.endsWith('.example') ? item.company.normalizedDomain : `${item.company.id}.example`;
      const company = { ...item.company, domain, normalizedDomain: domain,
        website: item.company.website ? `https://${domain}` : '', dataSource: 'demo' as const,
        contactEmail: item.company.contactEmail ? `sample-contact@${domain}` : null, linkedinUrl: null };
      const evidence = item.evidence.map(e => {
        const historicalFounder = e.type === 'FOUNDER_LED' && !/founder.*(?:ceo|president|currently|continues|still|leads|oversees)|(?:ceo|president).*founder/i.test(e.snippet);
        const type = historicalFounder ? 'OTHER' as const : e.type;
        const labels: Partial<Record<Evidence['type'], string>> = {
          FOUNDER_LED: 'Founder leadership wording', FAMILY_OWNED: 'Family ownership wording',
          INDEPENDENT: 'Private ownership wording; investors not verified',
          OWNER_OPERATED: 'Owner-operation wording',
        };
        return { ...e, type, claim: historicalFounder ? 'Historical founder mention; current role not verified' : labels[type] ?? e.claim,
          sourceUrl: `https://${domain}${new URL(e.sourceUrl).pathname}` };
      });
      validList.push({ company, evidence });
    }
  }

  return {
    validList,
    duplicates,
    totalCount: DEMO_COMPANIES_DATA.length,
    validCount: validList.length,
    duplicateCount: duplicates.length,
  };
}
